const LOCALE_TO_COUNTRY_CODE: Record<SupportedLocale, string[]> = {
  en: ['US', 'GB', 'CA', 'AU'],
  vi: ['VN'],
  de: ['DE', 'AT', 'CH'],
  fr: ['FR', 'BE', 'CH', 'CA'],
  es: ['ES', 'MX', 'AR', 'CL', 'CO'],
  ja: ['JP'],
  ko: ['KR'],
  zh: ['CN', 'TW', 'HK', 'SG'],
};

export function getLocalizedHolidayTitle(
  event: {
    name: string;
    localName: string;
    countryCode?: string;
    type: 'public_holiday' | 'birthday';
  },
  locale: SupportedLocale
): string {
  if (event.type === 'public_holiday') {
    const matchingCountries = LOCALE_TO_COUNTRY_CODE[locale] || [];
    if (event.countryCode && matchingCountries.includes(event.countryCode.toUpperCase())) {
      return event.localName || event.name;
    }
  }
  return event.name;
}
