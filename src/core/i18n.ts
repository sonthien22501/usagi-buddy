/**
 * Zero-dependency internationalization engine for Usagi Buddy (#18)
 * Supports English (en), Vietnamese (vi), German (de), French (fr),
 * Spanish (es), Japanese (ja), Korean (ko), and Chinese (zh).
 */

export type SupportedLocale = 'en' | 'vi' | 'de' | 'fr' | 'es' | 'ja' | 'ko' | 'zh';

